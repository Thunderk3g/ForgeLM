"""Render experiments/RESULTS.md from the JSON in experiments/results/.

    python experiments/report.py

Every number in RESULTS.md comes from a result file, so the report cannot
drift from what was measured.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
RES = HERE / "results"


def load(name):
    path = RES / f"{name}.json"
    return json.loads(path.read_text()) if path.is_file() else None


def pct(x, nd=1):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{100 * x:.{nd}f}%"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def mean_std(values, as_pct=True, nd=1):
    m, s = float(np.mean(values)), float(np.std(values))
    if as_pct:
        return f"{100 * m:.{nd}f}" + (f" ± {100 * s:.{nd}f}" if len(values) > 1 else "")
    return f"{m:.3f}" + (f" ± {s:.3f}" if len(values) > 1 else "")


out = ["# Experiment results", "",
       "Generated by `python experiments/report.py` from `experiments/results/*.json`. "
       "Re-run everything with `bash experiments/run_all.sh`.", ""]

env = None
for name in ("e1_banking77_ladder", "e2_teacher_distillation", "e4_tabular", "e6_unfair_terms"):
    data = load(name)
    if data:
        env = data["environment"]
        break
if env:
    out += ["## Test machine", "",
            f"{env['cpu']}, {env['cores']} cores, {env['ram_gb']} GiB RAM, no GPU. "
            f"CPU features: {', '.join(env['cpu_flags'])}.", "",
            "Packages: " + ", ".join(f"{k} {v}" for k, v in sorted(env["packages"].items())) + ".", "",
            "This is a shared cloud VM. Accuracy and calibration figures are reproducible; latency and "
            "training-time figures are indicative only and should be re-measured on the target hardware. "
            "Nothing here was run on a GPU.", ""]

# ---------------------------------------------------------------- E1
e1 = load("e1_banking77_ladder")
if e1:
    ds = e1["dataset"]
    out += ["## E1. Student ladder on Banking77", "",
            f"**Question.** With 8, 32 or all labels per class, which LLM-free student is most accurate, how "
            f"well calibrated is it, and what does it cost on a CPU?", "",
            f"**Setup.** {ds['classes']} banking intents, {ds['test']} test texts. {ds['calibration_anchor']} "
            f"training texts (5 per class) are held out to fit the confidence temperature and are never "
            f"trained on. Few-shot rows are the mean ± standard deviation over 3 random draws; full-data rows "
            f"are one run. No hyper-parameter search: the linear-head students use library defaults, and the "
            f"fine-tuned encoder uses settings fixed in advance (learning rate 1e-4, batch 32, 64 tokens, "
            f"30 / 12 / 5 epochs), so it could score higher with tuning.", ""]
    groups = defaultdict(list)
    for r in e1["rows"]:
        groups[(r["student"], str(r["labels_per_class"]))].append(r)
    students = []
    for r in e1["rows"]:
        if r["student"] not in students:
            students.append(r["student"])
    regimes = ["0", "8", "32", "full"]
    rows = []
    for s in students:
        row = [s]
        for k in regimes:
            g = groups.get((s, k))
            row.append(mean_std([x["accuracy"] for x in g]) if g else "")
        rows.append(row)
    out += ["Accuracy (%) by labels per class:", "",
            table(["Student", "0 labels", "8 per class", "32 per class", f"all (~{ds['train_pool'] // ds['classes']} per class)"], rows), ""]
    rows = []
    for s in students:
        row = [s]
        for k in regimes:
            g = groups.get((s, k))
            row.append(f"{np.mean([x['ece'] for x in g]):.3f} → {np.mean([x['ece_calibrated'] for x in g]):.3f}"
                       if g else "")
        rows.append(row)
    out += ["Expected calibration error, before → after temperature scaling on the 385-example anchor "
            "(lower is better):", "", table(["Student", "0 labels", "8 per class", "32 per class", "all"], rows), ""]
    rows = []
    for s in students:
        if not any((s, k) in groups for k in regimes[1:]):
            continue  # the zero-shot student is not trained
        row = [s]
        for k in regimes[1:]:
            g = groups.get((s, k))
            row.append(f"{np.mean([x['train_seconds'] for x in g]):.0f} s" if g else "")
        rows.append(row)
    out += ["Training time on 4 CPU cores (embedding time included for the embedding students):", "",
            table(["Student", "8 per class", "32 per class", "all"], rows), ""]
    e1b = load("e1b_modernbert_full")
    e1c = load("e1c_serving")
    serving = e1c["serving"] if e1c else list(e1["serving"]) + (e1b["serving"] if e1b else [])
    acc = {s: np.mean([x["accuracy"] for x in groups[(s, "full")]]) for s in students if (s, "full") in groups}
    if e1b:
        for r in e1b["rows"]:
            acc[r["student"]] = r["accuracy"]
            out_mb = r
    rows = [[s["student"], pct(acc.get(s["student"])), f"{s['latency_ms_p50']:.2f}", f"{s['latency_ms_p95']:.2f}",
             f"{s['throughput_per_s']:,.0f}", f"{s['artefact_mb']:.1f}", s.get("note", "")] for s in serving]
    out += ["Serving cost of the full-data students (PyTorch / numpy, before any ONNX export"
            + ("; measured in a separate run with nothing else using the machine" if e1c else "") + "):", "",
            table(["Student", "Accuracy", "p50 ms / text", "p95 ms / text", "texts / s (batch 32)", "Artefact MB",
                   "Note"], rows), ""]
    if e1b:
        r = e1b["rows"][0]
        out += [f"ModernBERT-base (149M), fine-tuned for {r.get('epochs')} epochs on the full set in a separate run: "
                f"{pct(r['accuracy'])} accuracy, ECE {r['ece']:.3f} → {r['ece_calibrated']:.3f}, "
                f"{r['train_seconds'] / 60:.0f} minutes of CPU training.", ""]

# ---------------------------------------------------------------- E2
e2 = load("e2_teacher_distillation")
if e2:
    t = e2["teacher"]
    out += ["## E2. A local LLM as teacher, with no human training labels", "",
            "**Question.** How close does a student trained only on a model's labels get to that model, and how "
            "does that compare with labelling a few examples by hand?", "",
            f"**Setup.** Banking77. Teacher: {t['model']} on CPU ({t['dtype']}), read through answer-letter "
            f"logits; a zero-shot embedding model shortlists 10 of the 77 intents per text "
            f"(top-10 recall {pct(e2['shortlister']['top10_recall_on_anchor'])}). The teacher labelled "
            f"{e2['pool_size']} unlabelled training texts at {t['seconds_per_item']} s per text. Scores are on "
            f"{e2['anchor_size']} human-labelled test texts the teacher never labelled for training.", ""]
    rows = [[name, pct(v["on_anchor"]["accuracy"]), pct(v["on_anchor"]["macro_f1"]), f"{v['on_anchor']['ece']:.3f}"]
            for name, v in e2["teachers_compared"].items()]
    out += ["Teachers on the anchor:", "", table(["Teacher", "Accuracy", "Macro F1", "ECE"], rows), ""]
    rows = [[r["teacher"], r["student"], r["labels"], r["min_confidence"], r["n_train"], pct(r["accuracy"]),
             f"{100 * r['student_minus_teacher_accuracy']:+.1f}", pct(r["agreement_with_teacher"])]
            for r in e2["students_on_teacher_labels"]]
    out += ["Students trained on teacher labels only:", "",
            table(["Teacher", "Student", "Labels", "Min. confidence", "Texts used", "Accuracy",
                   "vs teacher (points)", "Agrees with teacher"], rows), ""]
    rows = [[r["student"], r["trained_on"], pct(r["accuracy"]) + (f" ± {100 * r['accuracy_std']:.1f}" if "accuracy_std" in r else "")]
            for r in e2["references"]]
    out += ["Reference points on the same anchor (human labels):", "", table(["Student", "Trained on", "Accuracy"], rows), ""]

# ---------------------------------------------------------------- E3
e3 = load("e3_compression")
if e3:
    out += ["## E3. ONNX export and int8 quantisation behind a parity gate", "",
            "**Question.** After export and int8 quantisation, is it still the same classifier, and how much "
            "faster and smaller is it?", "",
            f"**Setup.** Fine-tuned Banking77 classifiers from E1. Gate: decision agreement with the PyTorch "
            f"model at least {pct(e3['gate']['min_agreement'], 0)} and accuracy drop at most "
            f"{100 * e3['gate']['max_accuracy_drop']:.0f} point, on all 3,080 test texts. "
            f"This CPU {'has' if e3['deployment_cpu_has_vnni'] else 'lacks'} VNNI.", ""]
    rows = []
    for m in e3["models"]:
        if "export_error" in m:
            rows.append([m["model"], "export failed", "", "", "", "", "", m["export_error"][:120]])
            continue
        for key, label in (("pytorch_fp32", "PyTorch fp32"), ("onnx_fp32", "ONNX fp32"), ("onnx_int8", "ONNX int8")):
            v = m[key]
            par = v.get("parity")
            rows.append([m["model"], label, pct(v["metrics"]["accuracy"]),
                         pct(par["agreement"]) if par else "reference", f"{v['size_mb']:.0f}",
                         f"{v['latency_ms_p50']:.1f}", f"{v['throughput_per_s']:,.0f}",
                         ("pass" if par["passed"] else "FAIL: " + "; ".join(par["reasons"])) if par else ""])
        rows.append([m["model"], "**recommended**", "", "", "", "", "", m["recommended"]["artefact"]])
    out += [table(["Model", "Format", "Accuracy", "Agreement with PyTorch", "MB", "p50 ms / text",
                   "texts / s (batch 32)", "Gate"], rows), ""]

# ---------------------------------------------------------------- E4
e4 = load("e4_tabular")
if e4:
    out += ["## E4. Tabular: classical models against an in-context foundation model", "",
            "**Question.** On risk-style tables, which model family wins at each training-set size, how well "
            "calibrated is it, and what does inference cost?", "",
            f"**Setup.** Two binary tasks, a fixed {e4['test_rows']}-row test set each, {e4['seeds']} random "
            f"training draws per size. {e4['hyperparameters'].capitalize()}: this compares out-of-the-box "
            f"behaviour, and a tuned GBDT would score somewhat higher. TabICL ({e4['tabicl']['licence']}) ran on "
            f"CPU and was not run above 2,000 rows.", ""]
    for ds, title in e4["datasets"].items():
        rows_ds = [r for r in e4["summary"] if r["dataset"] == ds]
        sizes = sorted({r["n_train"] for r in rows_ds})
        models = ["logreg", "hist_gbdt", "lightgbm", "ebm", "tabicl"]
        cell = {(r["model"], r["n_train"]): r for r in rows_ds}
        rows = []
        for m in models:
            row = [m]
            for n in sizes:
                r = cell.get((m, n))
                best = max((cell[(mm, n)]["roc_auc"] for mm in models if (mm, n) in cell), default=None)
                txt = f"{r['roc_auc']:.3f}" if r else "not run"
                row.append(f"**{txt}**" if r and abs(r["roc_auc"] - best) < 1e-9 else txt)
            rows.append(row)
        out += [f"**{title}** - ROC AUC (best per column in bold):", "",
                table(["Model"] + [f"{n:,} rows" for n in sizes], rows), ""]
        rows = []
        for m in models:
            row = [m]
            for n in sizes:
                r = cell.get((m, n))
                row.append(f"{r['brier']:.3f} / {r['ece']:.3f}" if r else "not run")
            rows.append(row)
        out += ["Brier score / ECE (lower is better):", "", table(["Model"] + [f"{n:,} rows" for n in sizes], rows), ""]
        rows = []
        for m in models:
            row = [m]
            for n in sizes:
                r = cell.get((m, n))
                row.append(f"{r['fit_seconds']:.1f} / {r['predict_seconds']:.1f}" if r else "not run")
            rows.append(row)
        out += [f"Seconds to fit / to score {e4['test_rows']:,} rows:", "",
                table(["Model"] + [f"{n:,} rows" for n in sizes], rows), ""]

# ---------------------------------------------------------------- E5
e5 = load("e5_cascade")
if e5:
    out += ["## E5. Abstention and cascades", "",
            "**Question.** If the small model answers only when confident, how much traffic can it take at a "
            "stated accuracy, and does sending the rest to a larger model help?", "",
            f"**Setup.** Full-data Banking77 students from E1. Temperature and threshold are both chosen on the "
            f"385-example anchor and applied unchanged to the 3,080 test texts. {e5['caveat'].capitalize()}.", ""]
    rows = []
    for s in e5["students"]:
        for t in s["targets"]:
            rows.append([s["student"], pct(s["test_accuracy"]), pct(t["target_accuracy"], 0),
                         pct(t["test_coverage"]) if t["target_reachable_on_anchor"] else "target not reachable",
                         pct(t["test_selective_accuracy"]) if t["target_reachable_on_anchor"] else "",
                         pct(t["oracle_cascade"]["cascade_accuracy"]) if t["target_reachable_on_anchor"] else ""])
    out += [table(["Student", "Accuracy answering everything", "Target", "Share answered by the student",
                   "Accuracy on that share", "Overall accuracy if a perfect reviewer takes the rest"], rows), ""]
    if e5.get("llm_escalation_model"):
        rows = []
        for s in e5["students"]:
            for t in s["targets"]:
                c = t.get("llm_cascade")
                if c and t["target_reachable_on_anchor"]:
                    rows.append([s["student"], pct(t["target_accuracy"], 0), pct(c["escalation_rate"]),
                                 pct(c["small_only_accuracy"]), pct(c["big_only_accuracy"]),
                                 pct(c["small_accuracy_on_escalated"]), pct(c["big_accuracy_on_escalated"]),
                                 pct(c["cascade_accuracy"])])
        out += ["Escalating to the real local LLM from E2 instead of a perfect reviewer (1,000 test texts):", "",
                table(["Student", "Target", "Escalated", "Student alone", "LLM alone",
                       "Student on escalated items", "LLM on escalated items", "Cascade accuracy"], rows), ""]

# ---------------------------------------------------------------- E6
e6 = load("e6_unfair_terms")
if e6:
    ds = e6["dataset"]
    out += ["## E6. Compliance screening: potentially unfair contract terms", "",
            "**Question.** To catch 90% of the unfair terms, how much of the text must a person read?", "",
            f"**Setup.** LexGLUE UNFAIR-ToS as a binary task ({pct(ds['positive_rate_test'])} positive), "
            f"{ds['train']} training, {ds['validation']} validation and {ds['test']} test sentences. "
            f"{e6['screening_rule'].capitalize()}.", ""]

    def e6_rows(items):
        return [[r["model"], f"{r['roc_auc']:.3f}", pct(r["screen_recall"]), pct(r["screen_precision"]),
                 pct(r["fraction_flagged_for_review"]), f"{r['f1_at_0.5']:.3f}"] for r in items]

    head = ["Model", "ROC AUC", "Recall at the screening threshold", "Precision there",
            "Share of sentences sent for review", "F1 at 0.5"]
    out += [table(head, e6_rows(e6["rows"])), ""]
    if e6.get("llm_teacher"):
        t = e6["llm_teacher"]
        out += [f"Students trained with no human labels, on {t['model']} soft labels "
                f"({t['seconds_per_item']} s per sentence; the teacher marked "
                f"{pct(t['teacher_positive_rate_on_pool'])} of the pool positive, the true rate is "
                f"{pct(t['true_positive_rate_on_pool'])}):", "", table(head, e6_rows(t["students"])), ""]
    out += ["Most indicative n-grams for the unfair class in the TF-IDF model: "
            + ", ".join(f"`{g.strip()}`" for g in e6["tfidf_top_ngrams_for_unfair"]) + ".", ""]

(HERE / "RESULTS.md").write_text("\n".join(out))
print(f"wrote {HERE / 'RESULTS.md'} ({len(out)} lines)")
